#!/usr/bin/env node
/**
 * "From the dev" announcements: signs website/public/announcements.json with the maintainer's
 * ed25519 key so the app only trusts entries Angel published. The private key stays outside the repo.
 *
 *   node scripts/announce.mjs keygen
 *   node scripts/announce.mjs list
 *   node scripts/announce.mjs poll <id> --title T --ends YYYY-MM-DD --option "A" --option "B"
 *   node scripts/announce.mjs notice <id> --title T --body B [--link https://ruforge.app/...]
 *   node scripts/announce.mjs remove <id>
 *   node scripts/announce.mjs verify
 */
import {
  createPrivateKey,
  createPublicKey,
  generateKeyPairSync,
  sign,
  verify,
} from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILE = path.join(root, 'website', 'public', 'announcements.json');
const TS_KEY = path.join(root, 'website', 'functions', '_shared', 'announcePubkey.ts');
const RS_KEY = path.join(root, 'src-tauri', 'src', 'announcements', 'pubkey.rs');
const KEY_PATH =
  process.env.RUFORGE_ANNOUNCE_KEY || path.join(os.homedir(), '.ruforge', 'announce-ed25519.pem');

const ID_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const LINK_PREFIX = 'https://ruforge.app/';
const SPKI_PREFIX_LEN = 12;

function die(msg) {
  console.error(msg);
  process.exit(1);
}

function validDate(s) {
  return typeof s === 'string' && DATE_RE.test(s) && !Number.isNaN(Date.parse(`${s}T00:00:00Z`));
}

function validateItem(it) {
  const e = (m) => die(`Invalid item "${it?.id}": ${m}`);
  if (!ID_RE.test(it.id || '')) e('id must be kebab-case');
  if (it.kind !== 'notice' && it.kind !== 'poll') e('kind must be notice or poll');
  if (!it.title || it.title.length > 80) e('title required, max 80 chars');
  if (it.kind === 'notice' && !it.body) e('notice needs a body');
  if (it.body && it.body.length > 280) e('body max 280 chars');
  if (it.kind === 'poll' && it.body) console.warn(`Warning: poll "${it.id}" has a body; the app never shows it. Drop it.`);
  if (!validDate(it.published)) e('published must be YYYY-MM-DD');
  if (it.ends !== undefined && !validDate(it.ends)) e('ends must be YYYY-MM-DD');
  if (it.kind === 'poll') {
    if (!Array.isArray(it.options) || it.options.length < 2 || it.options.length > 6) {
      e('poll needs 2 to 6 options');
    }
    const ids = new Set();
    for (const o of it.options) {
      if (!o.id || !o.label || o.label.length > 60) e('option label required, max 60 chars');
      if (ids.has(o.id)) e('duplicate option id');
      ids.add(o.id);
    }
    if (it.link !== undefined) e('polls take no link');
  } else {
    if (it.options !== undefined) e('notices take no options');
    if (it.link !== undefined && !String(it.link).startsWith(LINK_PREFIX)) {
      e(`link must start with ${LINK_PREFIX}`);
    }
  }
}

function rawPublicKey(pub) {
  return pub.export({ type: 'spki', format: 'der' }).subarray(SPKI_PREFIX_LEN);
}

function loadPrivate() {
  if (!fs.existsSync(KEY_PATH)) die(`No signing key at ${KEY_PATH}. Run: node scripts/announce.mjs keygen`);
  return createPrivateKey(fs.readFileSync(KEY_PATH));
}

function readEnvelope() {
  const env = JSON.parse(fs.readFileSync(FILE, 'utf8'));
  const bytes = Buffer.from(env.payload, 'base64');
  return { env, bytes, payload: JSON.parse(bytes.toString('utf8')) };
}

function write(payload) {
  for (const it of payload.items) validateItem(it);
  const ids = payload.items.map((i) => i.id);
  if (new Set(ids).size !== ids.length) die('Duplicate item ids');
  const bytes = Buffer.from(JSON.stringify(payload), 'utf8');
  const sig = sign(null, bytes, loadPrivate()).toString('base64');
  fs.mkdirSync(path.dirname(FILE), { recursive: true });
  fs.writeFileSync(FILE, `${JSON.stringify({ payload: bytes.toString('base64'), sig })}\n`);
}

function writeKeyFiles(hex) {
  fs.mkdirSync(path.dirname(TS_KEY), { recursive: true });
  fs.writeFileSync(
    TS_KEY,
    `// Generated by scripts/announce.mjs keygen. Public half only.\nexport const ANNOUNCE_PUBKEY_HEX = "${hex}";\n`,
  );
  const bytes = hex.match(/../g).map((b) => `0x${b}`);
  const rows = [];
  for (let i = 0; i < 32; i += 8) rows.push(`    ${bytes.slice(i, i + 8).join(', ')},`);
  fs.mkdirSync(path.dirname(RS_KEY), { recursive: true });
  fs.writeFileSync(
    RS_KEY,
    `//! Generated by scripts/announce.mjs keygen. Public half only.\n\npub const ANNOUNCE_PUBKEY: [u8; 32] = [\n${rows.join('\n')}\n];\n`,
  );
}

function flags(args) {
  const out = { _: [], option: [] };
  for (let i = 0; i < args.length; i++) {
    if (args[i].startsWith('--')) {
      const k = args[i].slice(2);
      const v = args[++i];
      if (v === undefined) die(`--${k} needs a value`);
      if (k === 'option') out.option.push(v);
      else out[k] = v;
    } else out._.push(args[i]);
  }
  return out;
}

function today() {
  return new Date().toISOString().slice(0, 10);
}

function hint(msg) {
  console.log('\nPublish (dry-run first):');
  console.log('  node scripts/publish-snapshot.mjs --only website/public/announcements.json --dry-run');
  console.log(
    `  RUFORGE_PUBLISH=1 node scripts/publish-snapshot.mjs --only website/public/announcements.json "${msg}"`,
  );
}

const [cmd, ...rest] = process.argv.slice(2);

if (cmd === 'keygen') {
  if (fs.existsSync(KEY_PATH)) die(`Refusing to overwrite existing key at ${KEY_PATH}`);
  const { privateKey, publicKey } = generateKeyPairSync('ed25519');
  fs.mkdirSync(path.dirname(KEY_PATH), { recursive: true });
  fs.writeFileSync(KEY_PATH, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
  const hex = rawPublicKey(publicKey).toString('hex');
  writeKeyFiles(hex);
  if (!fs.existsSync(FILE)) write({ version: 1, items: [] });
  console.log(`Private key: ${KEY_PATH}\nPublic key (hex): ${hex}`);
} else if (cmd === 'list') {
  const { payload } = readEnvelope();
  if (!payload.items.length) console.log('(no announcements)');
  for (const it of payload.items) {
    console.log(`${it.id}  ${it.kind}  ${it.published}${it.ends ? ` -> ${it.ends}` : ''}  ${it.title}`);
  }
} else if (cmd === 'poll' || cmd === 'notice') {
  const f = flags(rest);
  const id = f._[0];
  if (!id) die(`Usage: announce.mjs ${cmd} <id> --title T --body B ...`);
  const { payload } = readEnvelope();
  if (payload.items.some((i) => i.id === id)) die(`Id "${id}" already exists`);
  if (cmd === 'poll' && f.body) die('Polls show only the question and options; drop --body.');
  const item = { id, kind: cmd, title: f.title, body: f.body ?? '', published: today() };
  if (cmd === 'poll') {
    if (!f.ends) die('poll needs --ends YYYY-MM-DD');
    item.ends = f.ends;
    item.options = f.option.map((label, i) => ({ id: String.fromCharCode(97 + i), label }));
  } else if (f.link) item.link = f.link;
  payload.items.push(item);
  write(payload);
  console.log(`Added ${cmd} "${id}".`);
  hint(`Announcement: ${id}`);
} else if (cmd === 'remove') {
  const id = rest[0];
  const { payload } = readEnvelope();
  if (!payload.items.some((i) => i.id === id)) die(`No item "${id}"`);
  payload.items = payload.items.filter((i) => i.id !== id);
  write(payload);
  console.log(`Removed "${id}".`);
  hint(`Announcement removed: ${id}`);
} else if (cmd === 'verify') {
  const { env, bytes, payload } = readEnvelope();
  const pub = createPublicKey(loadPrivate());
  const ok = verify(null, bytes, pub, Buffer.from(env.sig, 'base64'));
  if (!ok) die('Signature does not match the local key');
  if (payload.version !== 1) die('Unsupported payload version');
  payload.items.forEach(validateItem);
  const tsHex = fs.readFileSync(TS_KEY, 'utf8').match(/"([0-9a-f]{64})"/)?.[1];
  if (tsHex !== rawPublicKey(pub).toString('hex')) die('announcePubkey.ts does not match the signing key');
  console.log(`OK: ${payload.items.length} item(s), signature valid.`);
} else {
  die('Commands: keygen | list | poll | notice | remove | verify');
}
